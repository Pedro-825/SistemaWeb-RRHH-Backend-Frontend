/* PRIMER ESTRUCTURA DE BASE DE DATOS PARA EL HOSPITAL SAN GABRIEL */

CREATE TABLE rol (
    id_rol SERIAL PRIMARY KEY,
    nombre_rol VARCHAR(50) NOT NULL UNIQUE,
    creado_el TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    actualizado_el TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    activo BOOLEAN DEFAULT TRUE
);

CREATE TABLE departamento(
    id_dpto INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR (100) NOT NULL,
    cod_dpto VARCHAR (20) UNIQUE ,
    ubicacion VARCHAR (100),
    jefe_dpto BIGINT ,
    creado_el TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    actualizado_el TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    activo BOOLEAN DEFAULT TRUE
);

CREATE TABLE empleado(
    id_empleado BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres VARCHAR (100) NOT NULL,
    apellidos VARCHAR (100) NOT NULL,
    doc_identidad VARCHAR (15) NOT NULL DEFAULT 'DNI' CHECK (doc_identidad IN('DNI','CE')),
    numero_di VARCHAR (15) UNIQUE NOT NULL,
    fecha_nac DATE NOT NULL,
    sexo VARCHAR(1) NOT NULL CHECK (sexo IN ('F', 'M')),
    estado_civil VARCHAR(20) DEFAULT 'SOLTERO' CHECK (estado_civil IN ('SOLTERO', 'CASADO', 'DIVORCIADO', 'VIUDO', 'CONVIVIENTE')),
    direccion VARCHAR (80) NOT NULL ,
    correo VARCHAR (50) NOT NULL,
    telefono VARCHAR (15),
    estado VARCHAR (30) NOT NULL DEFAULT 'ACTIVO' CHECK (estado IN('ACTIVO','LICENCIA','SUSPENDIDO','DESVINCULADO')),
    huella_template TEXT,
    saldo_vacaciones INT DEFAULT 30,
    creado_el TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_el TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_desvinculacion TIMESTAMP
);

ALTER TABLE departamento ADD CONSTRAINT fk_jefe_dpto FOREIGN KEY (jefe_dpto) REFERENCES empleado(id_empleado);


CREATE OR REPLACE FUNCTION fn_calcular_tardanza()
RETURNS TRIGGER AS $$
DECLARE
    v_id_horario INT;
    v_h_esperada TIME;
    v_tolerancia INT;
BEGIN
    SELECT id_horario INTO v_id_horario FROM asignacion_horario
    WHERE id_empleado = NEW.id_empleado AND NEW.fecha BETWEEN fecha_desde AND fecha_hasta AND activo = TRUE LIMIT 1;
    IF v_id_horario IS NULL THEN RETURN NEW; END IF;
    SELECT hora_entrada, tolerancia INTO v_h_esperada, v_tolerancia FROM horario WHERE id_horario = v_id_horario;
    IF NEW.hora_entrada > (v_h_esperada + (v_tolerancia || ' minutes')::interval) THEN
        NEW.minutos_tardanza := EXTRACT(EPOCH FROM (NEW.hora_entrada - v_h_esperada)) / 60;
    ELSE
        NEW.minutos_tardanza := 0;
    END IF;
    NEW.id_horario := v_id_horario;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tr_entrada_asistencia BEFORE INSERT ON registro_asistencia
FOR EACH ROW EXECUTE FUNCTION fn_calcular_tardanza();

CREATE OR REPLACE FUNCTION fn_calcular_extras()
RETURNS TRIGGER AS $$
DECLARE
    v_h_salida_esperada TIME;
    v_umbral INT;
    v_minutos_reales INT;
BEGIN
    IF NEW.hora_salida IS NULL THEN RETURN NEW; END IF;
    SELECT hora_salida, umbral_extra INTO v_h_salida_esperada, v_umbral FROM horario WHERE id_horario = NEW.id_horario;
    v_minutos_reales := EXTRACT(EPOCH FROM (NEW.hora_salida - v_h_salida_esperada)) / 60;
    IF v_minutos_reales >= v_umbral THEN
        NEW.minutos_extra := v_minutos_reales;
    ELSE
        NEW.minutos_extra := 0;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tr_salida_asistencia BEFORE UPDATE OF hora_salida ON registro_asistencia
FOR EACH ROW EXECUTE FUNCTION fn_calcular_extras();

CREATE OR REPLACE FUNCTION fn_timestamp_update()
RETURNS TRIGGER AS $$
BEGIN
    NEW.actualizado_el = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tr_act_empleado BEFORE UPDATE ON empleado FOR EACH ROW EXECUTE FUNCTION fn_timestamp_update();
CREATE TRIGGER tr_act_contrato BEFORE UPDATE ON contrato FOR EACH ROW EXECUTE FUNCTION fn_timestamp_update();
CREATE TRIGGER tr_act_usuario BEFORE UPDATE ON usuario FOR EACH ROW EXECUTE FUNCTION fn_timestamp_update();
